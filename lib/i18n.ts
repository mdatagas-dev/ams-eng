const enMessages = messages.en
export type MessageKey = keyof typeof enMessages
const idMessages: Record<MessageKey, string> = messages.id

// ponytail: flat key dicts, no ICU/plurals; switch to next-intl if more locales or plurals appear.
export function getDictionary(lang: Language) {
  return lang === "en" ? enMessages : idMessages
}

export type Translate = (
  key: MessageKey,
  vars?: Record<string, string | number>
) => string

export function makeT(dict: Record<MessageKey, string>): Translate {
  return (key, vars) => {
    let text = dict[key]
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replaceAll(`{${name}}`, String(value))
      }
    }
    return text
  }
}
